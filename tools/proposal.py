def breeze_grid():
    """Wumpus 식 바람 추론 예: 4x3 격자."""
    S, X0, Y0 = 62, 30, 20
    cells = {
        (0, 2): ('#cfe8cf', '출발\n바람 없음'), (1, 2): ('#fde9b8', '바람'), (0, 1): ('#cfe8cf', '바람 없음'),
        (1, 1): ('#e3f3e3', '안전\n(증명)'), (2, 2): ('#f6c9c4', '구덩이!\n(증명)'), (0, 0): ('#e3f3e3', '안전\n(증명)'),
    }
    out = [f'<svg viewBox="0 0 {X0 * 2 + S * 4 + 260} {Y0 * 2 + S * 3 + 10}" width="150mm" xmlns="http://www.w3.org/2000/svg" {F}>']
    for y in range(3):
        for x in range(4):
            fill, lab = cells.get((x, y), ('#f4f4f4', '?'))
            px, py = X0 + x * S, Y0 + y * S
            out.append(f'<rect x="{px}" y="{py}" width="{S}" height="{S}" fill="{fill}" stroke="#333" stroke-width="1.2"/>')
            lines = lab.split('\n')
            for i, ln in enumerate(lines):
                out.append(f'<text x="{px + S / 2}" y="{py + S / 2 + (i - (len(lines) - 1) / 2) * 15 + 5}" font-size="12.5" text-anchor="middle">{ln}</text>')
    tx = X0 + 4 * S + 22
    notes = ['① (0,2) 에 바람이 없다', '   → 이웃 (1,2) (0,1) 은 안전', '② (1,2) 에 바람이 있다',
             '   → (2,2) 나 (1,1) 에 구덩이', '③ (0,1) 에 바람이 없다', '   → (1,1) (0,0) 은 안전',
             '④ ② 와 ③ 을 합치면', '   → (2,2) 가 구덩이']
    for i, n in enumerate(notes):
        out.append(f'<text x="{tx}" y="{Y0 + 22 + i * 22}" font-size="13">{n}</text>')
    out.append('</svg>')
    return ''.join(out)




